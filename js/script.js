function injectHreflangTags() {
  const articleIdMatch = window.location.pathname.match(/\/articles\/(\d+)/);
  const currentId = articleIdMatch ? articleIdMatch[1] : null;
  if (!currentId || CLUSTER_ARTICLE_IDS.indexOf(currentId) === -1) return;

	// Remove ZenDesk's autogenerated hreflang tags
  const managedHreflangs = HREFLANG_ENTRIES.map(function (e) { return e.hreflang; });
  document.querySelectorAll('link[rel="alternate"][hreflang]').forEach(function (el) {
    if (managedHreflangs.indexOf(el.getAttribute("hreflang")) !== -1) {
      el.parentNode.removeChild(el);
    }
  });

  HREFLANG_ENTRIES.forEach(function (entry) {
    const link = document.createElement("link");
    link.setAttribute("rel", "alternate");
    link.setAttribute("hreflang", entry.hreflang);
    link.setAttribute("href", entry.url);
    document.head.appendChild(link);
  });
}

